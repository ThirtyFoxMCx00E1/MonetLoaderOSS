#!/usr/bin/env python3
# 3.9.1-mp: builds cpp/script/modules/mimgui/embedded_lua.h from dist/lib (mimgui is built into MonetLoader for MP,
# so a phone without moonloader/lib/mimgui - or with a broken copy shipped by a mod - still runs mimgui scripts).
# Run again after changing dist/lib/mimgui/*.lua:  python3 tools/embed_lua.py
import os
ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
MODS = [("mimgui", "dist/lib/mimgui/init.lua"),
        ("mimgui.imgui", "dist/lib/mimgui/imgui.lua"),
        ("mimgui.cdefs", "dist/lib/mimgui/cdefs.lua"),
        ("monethook", "dist/lib/monethook.lua")]
out = ["// generated by tools/embed_lua.py - do not edit", "#pragma once", "#include <cstddef>", "#include <cstring>", "",
       "namespace embedded_lua {", "struct module { const char* name; const char* chunk_name; const char* source; std::size_t size; };", ""]
names = []
for i, (name, path) in enumerate(MODS):
    data = open(os.path.join(ROOT, path), "rb").read()
    out.append("static const unsigned char m%d[] = {" % i)
    for j in range(0, len(data), 24):
        out.append("  " + ",".join(str(b) for b in data[j:j + 24]) + ",")
    out.append("  0 };")
    names.append((name, "@" + "moonloader/lib/" + path.split("dist/lib/")[1] + " (built-in)", "m%d" % i, len(data)))
out.append("static const module modules[] = {")
for n, c, v, sz in names:
    out.append('  { "%s", "%s", reinterpret_cast<const char*>(%s), %d },' % (n, c, v, sz))
out.append("};")
out += ["inline const module* find(const char* name)", "{",
        "  for (const module& m : modules) {", "    if (std::strcmp(m.name, name) == 0) {", "      return &m;", "    }", "  }",
        "  return nullptr;", "}", "} // namespace embedded_lua", ""]
open(os.path.join(ROOT, "cpp/script/modules/mimgui/embedded_lua.h"), "w").write("\n".join(out))
print("ok", [(n, sz) for n, _, _, sz in names])
